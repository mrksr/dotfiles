#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# ///
"""Write INDEX.md for a cowork repo from the front matter of each project's README.md.

Projects are top-level folders named YYYY-MM-DD-topic (older: YYYY-MM-topic). Folders without front matter are listed as "no front matter yet",
so the index always covers every project.

Usage: build_index.py [repo root]   (default: current directory)
       build_index.py --check       print the index instead of writing it
"""

import re
import sys
from pathlib import Path

PROJECT = re.compile(r"^\d{4}-\d{2}-")
FIELDS = ("summary", "kind", "status", "tags")


def front_matter(readme: Path) -> dict[str, str | list[str]]:
    """Parse the simple YAML subset used in project READMEs: `key: value` and `key: [a, b]`."""
    if not readme.exists():
        return {}
    text = readme.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end == -1:
        return {}
    data: dict[str, str | list[str]] = {}
    for line in text[4:end].splitlines():
        key, sep, value = line.partition(":")
        if not sep or line.startswith((" ", "#")):
            continue
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            data[key.strip()] = [v.strip().strip("\"'") for v in value[1:-1].split(",") if v.strip()]
        else:
            data[key.strip()] = value.strip("\"'")
    return data


def cell(value: str | list[str] | None) -> str:
    if not value:
        return ""
    text = ", ".join(value) if isinstance(value, list) else value
    return text.replace("|", "\\|")


def build(root: Path) -> str:
    projects = sorted((p for p in root.iterdir() if p.is_dir() and PROJECT.match(p.name)), reverse=True)
    rows = ["| Project | Summary | Kind | Status | Tags |", "|---|---|---|---|---|"]
    missing = 0
    for project in projects:
        meta = front_matter(project / "README.md")
        if not meta:
            missing += 1
            meta = {"summary": "_no front matter yet_"}
        link = f"[{project.name}]({project.name}/)"
        rows.append("| " + " | ".join([link, *(cell(meta.get(f)) for f in FIELDS)]) + " |")
    header = [
        "# Index",
        "",
        f"{len(projects)} projects, newest first. Generated by `build_index.py` in the retro skill from each",
        "project's README front matter; edit the front matter, not this file.",
    ]
    if missing:
        header.append(f"{missing} projects have no front matter yet.")
    return "\n".join([*header, "", *rows, ""])


def main() -> None:
    args = [a for a in sys.argv[1:] if a != "--check"]
    root = Path(args[0] if args else ".").resolve()
    index = build(root)
    if "--check" in sys.argv:
        print(index)
    else:
        (root / "INDEX.md").write_text(index, encoding="utf-8")
        print(f"Wrote {root / 'INDEX.md'}")


if __name__ == "__main__":
    main()
